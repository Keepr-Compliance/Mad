/**
 * BACKLOG-4263 (sync 2.49) — in every 20261123* migration of the lane, its rollback file and its apply file,
 * lock_timeout is set before the first statement that takes a lock.
 *
 * Each file has exactly one lock_timeout statement, `SET LOCAL lock_timeout = '<n>ms|s'` (1 ms to 3 s), at top level.
 * No other top-level statement or DO block may touch lock_timeout (a plain SET, RESET, RESET ALL, DISCARD ALL,
 * set_config('lock_timeout', ...)); function bodies are not checked (they run later, when called).
 * Allowed before the lock_timeout statement: comments, and DO blocks that only read the catalogue: no CREATE, ALTER,
 * DROP, GRANT, REVOKE, LOCK, INSERT, UPDATE, DELETE, TRUNCATE, EXECUTE or PERFORM, no row lock, and every item after a
 * FROM, a JOIN or a comma in a FROM list is one of: pg_catalog.<name>, a parenthesised subquery or VALUES list, VALUES,
 * or a named set-returning function (SRF below). Anything else turns this red. CI has no database: this checks file
 * text only.
 */

import { readFileSync, readdirSync } from 'fs';
import { join } from 'path';

const REPO = join(__dirname, '../../..');
const MIGDIR = join(REPO, 'supabase/migrations');
const read = (p: string): string => readFileSync(join(REPO, p), 'utf8').replace(/\r\n?/g, '\n');

/**
 * Exempt as they are, each failing the rule for the reason given (expected problem text; a change to the file or to
 * the rule turns its entry red, so no other file can pass through it):
 * - E1 migration 20261123110000: its text is pinned by md5 in supabase/tests/backlog-4263-prod (expected.json and
 *   postcheck-20261123110000.sql).
 * - E1 apply file: checked equal to the E1 text by apply-wrappers-4263.test.ts and backlog-4263-sync2-erase/harness.py
 *   check.
 * - S1 rollback: generated from S1's text by backlog-4263-sync2-s1/gen.py and compared by its `check`.
 */
const ALLOWED_AS_IS: Record<string, string> = {
  // E1: no lock_timeout statement at all
  'supabase/migrations/20261123110000_backlog_4263_cloud_blob_erase.sql': 'no lock_timeout',
  'supabase/tests/backlog-4263-sync2-erase/apply-20261123110000.sql': 'no lock_timeout',
  // S1's rollback (generated by backlog-4263-sync2-s1/gen.py from S1's text): its pre-check reads three S1 tables
  'supabase/tests/backlog-4263-sync2-s1/rollback-20261123100000.sql':
    'before lock_timeout: DO $prerb4263s1$ DECLARE r record; v text; BEGIN FOR r IN SELECT * FROM (VALUE [FROM public.cloud_computer_moves), (SELECT co]',
};

/** Top-level statements with comments removed and string / dollar-quoted text kept (code only for keyword checks). */
export function statements(sql: string): { text: string; code: string; bare: string }[] {
  const out: { text: string; code: string; bare: string }[] = [];
  let text = '';
  let code = '';
  let bare = '';
  let i = 0;
  while (i < sql.length) {
    if (sql.startsWith('--', i)) {
      const j = sql.indexOf('\n', i);
      i = j < 0 ? sql.length : j;
      continue;
    }
    if (sql.startsWith('/*', i)) {
      const j = sql.indexOf('*/', i + 2);
      if (j < 0) throw new Error('unclosed comment');
      i = j + 2;
      text += ' ';
      code += ' ';
      bare += ' ';
      continue;
    }
    const c = sql[i];
    if (c === "'") {
      let j = i + 1;
      for (;;) {
        j = sql.indexOf("'", j);
        if (j < 0) throw new Error('unclosed literal');
        if (sql[j + 1] === "'") j += 2;
        else break;
      }
      text += sql.slice(i, j + 1);
      code += "''";
      bare += sql.slice(i, j + 1);
      i = j + 1;
      continue;
    }
    const d = c === '$' ? /^\$([A-Za-z_][A-Za-z0-9_]*)?\$/.exec(sql.slice(i)) : null;
    if (d && (i === 0 || !/[A-Za-z0-9_]/.test(sql[i - 1]))) {
      const end = sql.indexOf(d[0], i + d[0].length);
      if (end < 0) throw new Error(`unclosed ${d[0]}`);
      const body = sql.slice(i, end + d[0].length);
      text += body;
      // the body of a DO block or function is code too: strip its own comments and literals
      const inner = body.slice(d[0].length, body.length - d[0].length).replace(/--[^\n]*/g, ' ').replace(/\/\*[\s\S]*?\*\//g, ' ');
      code += ' ' + inner.replace(/'(?:[^']|'')*'/g, "''") + ' ';
      bare += ' ' + inner + ' ';
      i = end + d[0].length;
      continue;
    }
    if (c === ';') {
      if (text.trim()) out.push({ text: text.trim(), code: code.trim(), bare: bare.trim() });
      text = '';
      code = '';
      bare = '';
      i += 1;
      continue;
    }
    text += c;
    code += c;
    bare += c;
    i += 1;
  }
  if (text.trim()) out.push({ text: text.trim(), code: code.trim(), bare: bare.trim() });
  return out;
}

const LOCK_TIMEOUT = /^SET\s+LOCAL\s+lock_timeout\s*(?:=|TO)\s*'(\d+)(ms|s)'$/i;
const IS_FUNCTION = /^CREATE\s+(?:OR\s+REPLACE\s+)?FUNCTION\b/i;
const TOUCHES_TIMEOUT = /\block_timeout\b|\bRESET\s+ALL\b|\bDISCARD\s+ALL\b/i;
const TAKES_LOCK =
  /\b(CREATE|ALTER|DROP|GRANT|REVOKE|LOCK|INSERT|UPDATE|DELETE|TRUNCATE|EXECUTE|PERFORM|COPY|VACUUM|REINDEX|CLUSTER|REFRESH)\b|\bFOR\s+(NO\s+KEY\s+UPDATE|UPDATE|KEY\s+SHARE|SHARE)\b/i;
/** Set-returning functions accepted as a FROM item before the lock_timeout statement (they read no table). */
const SRF = ['unnest', 'jsonb_array_elements', 'jsonb_array_elements_text', 'jsonb_each', 'jsonb_object_keys', 'regexp_matches', 'generate_series'];
const ITEM_OK = new RegExp(`^(?:LATERAL\\s+)?(?:\\(|VALUES\\b|pg_catalog\\.[a-z_][a-z0-9_]*\\b(?!\\s*\\.)|(?:${SRF.join('|')})\\s*\\()`, 'i');
const ENDS_LIST = /^(WHERE|GROUP|ORDER|LIMIT|HAVING|UNION|EXCEPT|INTERSECT|WINDOW|OFFSET|FETCH|FOR|LOOP|THEN|INTO|ON|JOIN|INNER|LEFT|RIGHT|FULL|CROSS|NATURAL|RETURNING|ELSE|END|AND|OR|WHEN)\b/i;
const FROM_IN_CALL = /\b(extract|substring|trim|overlay|position)\s*$/i;

/** The first FROM / JOIN / comma item that is not on the list above, or null. code: comments and literals removed. */
export function fromProblem(code: string): string | null {
  for (const m of code.matchAll(/\b(FROM|JOIN)\b/gi)) {
    const at = m.index!;
    if (/\bDISTINCT\s+$/i.test(code.slice(0, at))) continue;
    // FROM inside extract(...) and similar calls is not a FROM list
    let d = 0;
    let k = at - 1;
    for (; k >= 0; k -= 1) {
      if (code[k] === ')' || code[k] === ']') d += 1;
      else if (code[k] === '(' || code[k] === '[') {
        if (d === 0) break;
        d -= 1;
      }
    }
    if (k >= 0 && code[k] === '(' && FROM_IN_CALL.test(code.slice(0, k))) continue;
    let pos = at + m[0].length;
    for (;;) {
      const rest = code.slice(pos).replace(/^\s+/, '');
      pos = code.length - rest.length;
      if (!ITEM_OK.test(rest)) return `${m[0].toUpperCase()} ${rest.slice(0, 40).replace(/\s+/g, ' ')}`;
      if (/^join$/i.test(m[0])) break;
      // skip this item (balanced brackets) to a top-level comma (next item) or the end of the FROM list
      let depth = 0;
      let next = -1;
      for (let q = pos; q < code.length; q += 1) {
        const c = code[q];
        if (c === '(' || c === '[') depth += 1;
        else if (c === ')' || c === ']') {
          if (depth === 0) break;
          depth -= 1;
        } else if (depth === 0 && c === ',') {
          next = q + 1;
          break;
        } else if (depth === 0 && c === ';') break;
        else if (depth === 0 && /[A-Za-z]/.test(c) && (q === 0 || !/[A-Za-z0-9_]/.test(code[q - 1])) && ENDS_LIST.test(code.slice(q))) break;
      }
      if (next < 0) break;
      pos = next;
    }
  }
  return null;
}

/** Why the file fails the rule, or null. */
export function problem(sql: string): string | null {
  const st = statements(sql);
  const ats = st.map((s, i) => (LOCK_TIMEOUT.test(s.text) ? i : -1)).filter((i) => i >= 0);
  for (const s of st) {
    if (IS_FUNCTION.test(s.text) || LOCK_TIMEOUT.test(s.text)) continue;
    if (TOUCHES_TIMEOUT.test(s.bare)) return `lock_timeout touched outside the one SET LOCAL: ${s.text.slice(0, 80).replace(/\s+/g, ' ')}`;
  }
  if (ats.length === 0) return 'no lock_timeout';
  if (ats.length > 1) return `${ats.length} lock_timeout statements`;
  const at = ats[0];
  const m = LOCK_TIMEOUT.exec(st[at].text)!;
  const ms = Number(m[1]) * (m[2].toLowerCase() === 's' ? 1000 : 1);
  if (ms < 1 || ms > 3000) return `lock_timeout ${m[1]}${m[2]} is not 1 ms to 3 s`;
  for (const s of st.slice(0, at)) {
    const head = `before lock_timeout: ${s.text.slice(0, 80).replace(/\s+/g, ' ')}`;
    if (!/^DO\s/i.test(s.text)) return head;
    const body = s.code.replace(/^DO\s/i, '');
    const hit = TAKES_LOCK.exec(body);
    if (hit) return `${head} [${hit[0]}]`;
    const from = fromProblem(body);
    if (from) return `${head} [${from}]`;
  }
  return null;
}

const LANE = readdirSync(MIGDIR).filter((f) => /^20261123\d{6}_.*\.sql$/.test(f)).sort();
const TESTS = join(REPO, 'supabase/tests');
const COMPANIONS = readdirSync(TESTS)
  .filter((d) => d.startsWith('backlog-4263-sync2'))
  .flatMap((d) => readdirSync(join(TESTS, d)).filter((f) => /^(apply|rollback)-20261123\d{6}\.sql$/.test(f)).map((f) => `supabase/tests/${d}/${f}`))
  .sort();
const FILES = [...LANE.map((f) => `supabase/migrations/${f}`), ...COMPANIONS];

describe('BACKLOG-4263 lock_timeout is set before the first statement that takes a lock', () => {
  it('finds the lane files', () => {
    expect(LANE.length).toBeGreaterThanOrEqual(5);
    expect(COMPANIONS.length).toBeGreaterThanOrEqual(8);
    for (const v of LANE.map((f) => f.slice(0, 14))) {
      expect(COMPANIONS.some((c) => c.endsWith(`rollback-${v}.sql`))).toBe(true);
    }
  });

  it.each(FILES)('%s', (f) => {
    const p = problem(read(f));
    if (f in ALLOWED_AS_IS) expect(`${f}: ${p}`).toBe(`${f}: ${ALLOWED_AS_IS[f]}`);
    else expect(`${f}: ${p}`).toBe(`${f}: null`);
  });

  it('the rule itself: a lock-taking statement moved above lock_timeout is reported; catalogue-only checks are not', () => {
    const s2 = read('supabase/migrations/20261123130000_backlog_4263_messages_up_server.sql');
    expect(problem(s2)).toBeNull();
    const line = "SET LOCAL lock_timeout = '3s';\n";
    expect(s2.split(line)).toHaveLength(2);
    const firstCreate = s2.indexOf('CREATE OR REPLACE FUNCTION');
    const fnEnd = s2.indexOf('$f$;', s2.indexOf('AS $f$', firstCreate) + 6) + 4;
    const moved = s2.replace(line, '').slice(0, fnEnd - line.length) + '\n' + line + s2.replace(line, '').slice(fnEnd - line.length);
    expect(moved.indexOf(line)).toBeGreaterThan(firstCreate);
    expect(problem(moved)).toMatch(/^before lock_timeout: CREATE OR REPLACE FUNCTION public\.cloud_upsert_messages/);
    expect(problem("DO $x$ BEGIN PERFORM 1 FROM pg_catalog.pg_proc; END $x$;\nSET LOCAL lock_timeout = '3s';")).toMatch(/^before lock_timeout: DO/);
    expect(problem("DO $x$ BEGIN IF NOT EXISTS (SELECT 1 FROM public.t) THEN RAISE EXCEPTION 'x'; END IF; END $x$;\nSET LOCAL lock_timeout = '3s';")).toMatch(/^before lock_timeout: DO/);
    expect(problem("DO $x$ BEGIN IF to_regclass('public.t') IS NULL THEN RAISE EXCEPTION 'x'; END IF; END $x$;\nSET LOCAL lock_timeout = '3s';\nCREATE TABLE public.t (a int);")).toBeNull();
    expect(problem("DO $x$ BEGIN IF r.a IS DISTINCT FROM r.b THEN RAISE EXCEPTION 'x'; END IF; END $x$;\nSET LOCAL lock_timeout = '3s';")).toBeNull();
    expect(problem("SET LOCAL lock_timeout = '10s';")).toMatch(/not 1 ms to 3 s/);
    const pre = (sel: string): string | null =>
      problem(`DO $x$ BEGIN IF EXISTS (${sel}) THEN NULL; END IF; END $x$;\nSET LOCAL lock_timeout = '3s';`);
    expect(pre('SELECT 1 FROM pg_catalog.pg_class c, pg_catalog.pg_namespace n WHERE c.relnamespace = n.oid')).toBeNull();
    expect(pre("SELECT 1 FROM unnest(ARRAY['a', 'b']) s, (VALUES (1)) v(a) WHERE s = 'a'")).toBeNull();
    expect(pre('SELECT extract(epoch FROM now())')).toBeNull();
    for (const bad of ['SELECT 1 FROM t', 'SELECT 1 FROM pg_catalog.pg_class c, public.t', 'SELECT 1 FROM "public"."t"', 'SELECT 1 FROM ONLY public.t',
      'SELECT 1 FROM pg_catalog.pg_class c JOIN t ON true', 'SELECT 1 FROM pg_catalog.pg_class c LEFT JOIN public.t x ON true',
      'SELECT 1 FROM "pg_catalog".pg_class', 'SELECT 1 FROM pg_catalog.pg_class.x', 'SELECT 1 FROM cron.job']) {
      expect(`${bad}: ${pre(bad)}`).toMatch(/\[(FROM|JOIN) /);
    }
    const lt = "SET LOCAL lock_timeout = '3s';";
    expect(problem(`${lt}\nRESET lock_timeout;`)).toMatch(/^lock_timeout touched outside/);
    expect(problem(`${lt}\nRESET ALL;`)).toMatch(/^lock_timeout touched outside/);
    expect(problem(`${lt}\nDISCARD ALL;`)).toMatch(/^lock_timeout touched outside/);
    expect(problem(`${lt}\nSELECT set_config('lock_timeout', '0', true);`)).toMatch(/^lock_timeout touched outside/);
    expect(problem(`${lt}\nDO $x$ BEGIN PERFORM set_config('lock_timeout', '0', true); END $x$;`)).toMatch(/^lock_timeout touched outside/);
    expect(problem("SET lock_timeout = '3s';")).toMatch(/^lock_timeout touched outside/);
    expect(problem(`${lt}\n${lt}`)).toBe('2 lock_timeout statements');
    expect(problem(`${lt}\nCREATE OR REPLACE FUNCTION public.f() RETURNS void LANGUAGE plpgsql AS $f$ BEGIN PERFORM set_config('lock_timeout', '1s', true); END $f$;`)).toBeNull();
    expect(problem('CREATE TABLE public.t (a int);')).toBe('no lock_timeout');
    expect(problem("-- SET LOCAL lock_timeout = '3s';\nCREATE TABLE public.t (a int);")).toBe('no lock_timeout');
  });
});
