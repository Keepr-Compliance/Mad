#!/usr/bin/env python3
"""BACKLOG-4263 PR-1: writes the apply file for 20261118100000 to the path given.

The apply file is one transaction: the migration text exactly as in the repo, the ledger row (the
migration text as its one statement), then a post-check DO that RAISEs (rolling back everything) unless:
- the reader and the tool have the md5(prosrc), SECURITY DEFINER, volatility, search_path, owner and
  EXECUTE grantees the file says (md5 computed offline from the file);
- the anon-callable mcp functions are exactly the nine earlier ones at their measured md5 plus the tool (10);
- there are 41 public functions named _?mcp_*;
- the call log tool CHECK names list_all_deals and the four earlier tools;
- the ledger holds exactly one row for 20261118100000.
Usage: gen-apply.py <out path>
"""
import ast, hashlib, os, re, subprocess, sys

here = os.path.dirname(os.path.abspath(__file__))
root = subprocess.check_output(['git', '-C', here, 'rev-parse', '--show-toplevel'], text=True).strip()
MIGP = 'supabase/migrations/20261118100000_backlog_4263_mcp_list_all_deals.sql'
MIG = open(os.path.join(root, MIGP)).read()
sys.path.insert(0, here)
src = open(os.path.join(here, 'harness.py')).read()
ANON9 = ast.literal_eval(re.search(r'ANON9 = (\{.*?\n\})', src, re.S).group(1))


def prosrc(name):
    i = MIG.index('CREATE OR REPLACE FUNCTION public.%s(' % name)
    b0 = MIG.index('AS $fn$', i) + len('AS $fn$')
    return MIG[b0:MIG.index('$fn$;', b0)]


md5 = lambda s: hashlib.md5(s.encode('utf-8')).hexdigest()
R, T = md5(prosrc('_mcp_r_list_all_deals')), md5(prosrc('mcp_list_all_deals'))
TAG = '$mig4263$'
assert TAG not in MIG
lit = lambda s: "'" + s.replace("'", "''") + "'"
anon_vals = ',\n      '.join('(%s, %s)' % (lit('public.' + k), lit(v)) for k, v in sorted(ANON9.items()))
out = """-- Apply file for %(p)s (BACKLOG-4263 PR-1). Generated by supabase/tests/backlog-4263/gen-apply.py.
-- file md5 %(fm)s ; reader md5(prosrc) %(r)s ; tool md5(prosrc) %(t)s
-- One transaction. The post-check RAISEs (and so rolls everything back) unless the catalog is as stated.
BEGIN;
%(mig)s
INSERT INTO supabase_migrations.schema_migrations (version, name, statements)
VALUES ('20261118100000', 'backlog_4263_mcp_list_all_deals', ARRAY[%(tag)s%(mig)s%(tag)s]);
DO $post4263$
DECLARE bad text := '';
BEGIN
  IF (SELECT md5(p.prosrc) <> %(rl)s OR NOT p.prosecdef OR p.provolatile <> 's' OR p.proowner <> 'mcp_reader'::regrole
             OR coalesce(array_to_string(p.proconfig, ','), '') <> 'search_path=""'
             OR (SELECT string_agg(a.grantee::regrole::text, ',' ORDER BY a.grantee::regrole::text) FROM aclexplode(p.proacl) a WHERE a.privilege_type = 'EXECUTE') <> 'mcp_reader,postgres'
        FROM pg_proc p WHERE p.oid = to_regprocedure('public._mcp_r_list_all_deals(text,date,date,uuid)')) IS NOT FALSE THEN
    bad := bad || 'reader ';
  END IF;
  IF (SELECT md5(p.prosrc) <> %(tl)s OR NOT p.prosecdef OR p.provolatile <> 'v' OR p.proowner <> 'postgres'::regrole
             OR coalesce(array_to_string(p.proconfig, ','), '') <> 'search_path=""'
             OR (SELECT string_agg(a.grantee::regrole::text, ',' ORDER BY a.grantee::regrole::text) FROM aclexplode(p.proacl) a WHERE a.privilege_type = 'EXECUTE') <> 'anon,postgres'
        FROM pg_proc p WHERE p.oid = to_regprocedure('public.mcp_list_all_deals(text,bytea,text,text,text,text,text)')) IS NOT FALSE THEN
    bad := bad || 'tool ';
  END IF;
  IF (WITH e(sig, m) AS (VALUES
      %(anon)s,
      ('public.mcp_list_all_deals(text,bytea,text,text,text,text,text)', %(tl)s)),
      a AS (SELECT p.oid, md5(p.prosrc) AS m FROM pg_proc p
             WHERE p.pronamespace = 'public'::regnamespace AND p.proname ~ '^_?mcp_' AND has_function_privilege('anon', p.oid, 'EXECUTE'))
      SELECT count(*) FROM e FULL JOIN a ON a.oid = to_regprocedure(e.sig) WHERE e.sig IS NULL OR a.oid IS NULL OR a.m IS DISTINCT FROM e.m) <> 0
     OR (SELECT count(*) FROM pg_proc p WHERE p.pronamespace = 'public'::regnamespace AND p.proname ~ '^_?mcp_' AND has_function_privilege('anon', p.oid, 'EXECUTE')) <> 10 THEN
    bad := bad || 'anon_set ';
  END IF;
  IF (SELECT count(*) FROM pg_proc p WHERE p.pronamespace = 'public'::regnamespace AND p.proname ~ '^_?mcp_') <> 41 THEN
    bad := bad || 'mcp_count ';
  END IF;
  IF (SELECT pg_get_constraintdef(c.oid) FROM pg_constraint c WHERE c.conrelid = 'public.mcp_call_log'::regclass AND c.conname = 'mcp_call_log_tool_check')
     IS DISTINCT FROM 'CHECK (((tool IS NULL) OR (tool = ANY (ARRAY[''get_status''::text, ''list_deals''::text, ''get_deal''::text, ''get_deal_checklists''::text, ''list_all_deals''::text]))))' THEN
    bad := bad || 'tool_check ';
  END IF;
  IF (SELECT count(*) FROM supabase_migrations.schema_migrations WHERE version = '20261118100000') <> 1 THEN
    bad := bad || 'ledger ';
  END IF;
  IF bad <> '' THEN
    RAISE EXCEPTION 'P4263_POSTCHECK_FAILED %%', bad;
  END IF;
END
$post4263$;
COMMIT;
""" % {'p': MIGP, 'fm': md5(MIG), 'r': R, 't': T, 'mig': MIG, 'tag': TAG, 'rl': lit(R), 'tl': lit(T), 'anon': anon_vals}
open(sys.argv[1], 'w').write(out)
print('written %s (file md5 %s, reader %s, tool %s)' % (sys.argv[1], md5(MIG), R, T))
