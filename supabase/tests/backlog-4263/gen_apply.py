rows = ',\n      '.join('(%s, %s, %s, %s, %s, %s, %s, %s, %s, %s)' % (lit(k), lit(v['md5']), 'true' if v['secdef'] else 'false', lit(v['vol']), lit(v['own']),
        lit(v['cfg']), str(v['anon']).lower(), str(v['authenticated']).lower(), str(v['service_role']).lower(), str(v['public']).lower()) for k, v in sorted(facts.items()))
