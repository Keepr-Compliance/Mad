def create(sql, name):
    """(statement text from CREATE to '$tag$;' inclusive, body, grant lines after it) of the last CREATE of public.<name>."""
    starts = [m.start() for m in re.finditer(r'^CREATE (?:OR REPLACE )?FUNCTION public\.' + re.escape(name) + r'\(', sql, re.M)]
    assert starts, name
    s = starts[-1]
    a = re.compile(r'\bAS (\$[A-Za-z_]*\$)').search(sql, s)
    b1 = sql.index(a.group(1), a.end())
    end = sql.index(';\n', b1) + 1
    grants = []
    for line in sql[end + 1:].split('\n'):
        if re.match(r'^(REVOKE|GRANT) .*FUNCTION public\.' + re.escape(name) + r'\(', line):
            grants.append(line)
        else:
            break
    return sql[s:end], sql[a.end():b1], grants


def sub1(text, old, new):
    assert text.count(old) == 1, ('pattern must occur once', old[:90], text.count(old))
    return text.replace(old, new)


