def dq(s, tag):
    assert tag not in s, tag
    return tag + '\n' + s + '\n' + tag


def body_of(text, fn):
    start = f'CREATE OR REPLACE FUNCTION public.{fn}('
    assert text.count(start) == 1, fn
    i = text.index(start)
    b0 = text.index('AS $fn$', i) + len('AS $fn$')
    return text[b0:text.index('$fn$', b0)]


