def variant_rows(mid, kind, ops, show):
    """The (ord, stmt) rows of one variant: a replaced, dropped or added statement each."""
    st = list(STMTS[kind])
    rows = {}
    adds = []
    for op in ops:
        if op[0] in ('replace', 'drop', 'after'):
            frag = op[1]
            exact = [i for i, s in enumerate(st) if s is not None and s == frag]
            hits = exact or [i for i, s in enumerate(st) if s is not None and frag in s]
            n = len(exact) if exact else sum(s.count(frag) for s in st if s is not None)
            if n != 1:
                raise SystemExit(f'MUTATION NOT APPLIED {mid}: fragment matched {n} times in {kind}: {frag[:120]!r}')
            i = hits[0]
            if op[0] == 'replace':
                st[i] = st[i].replace(frag, op[2])
                rows[i + 1] = st[i]
            elif op[0] == 'drop':
                st[i] = None
                rows[i + 1] = None
            else:
                adds.append((i + 1.5, op[2]))
        else:
            adds.append((len(STMTS[kind]) + 1 + len(adds), op[1]))
    if show:
        print(f'MUTATION APPLIED {mid} ({kind}; statements changed {len(rows)}, added {len(adds)})')
        for o in ops:
            print('  - ' + o[1].strip().splitlines()[0][:150])
            if o[0] in ('replace', 'after'):
                print('  + ' + (o[2].strip().splitlines() or ['(removed)'])[0][:150])
    out = [(float(k), v) for k, v in rows.items()] + adds
    assert out, mid
    return out


def rows_sql(variant, kind, rows, k0):
    out = []
    for j, (ordv, stmt) in enumerate(rows):
        tag = f'$s{k0}_{j}$'
        val = 'NULL' if stmt is None else dq(stmt, tag)
        out.append(f"INSERT INTO pg_temp.t_tn VALUES ('{variant}', '{kind}', {ordv}, {val});\n")
    return ''.join(out)


