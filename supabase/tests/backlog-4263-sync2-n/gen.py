def unwrap(raw):
    text = '\n'.join(l for l in raw.replace('\r\n', '\n').split('\n') if not l.startswith('kt-sql: ')).strip()
    try:
        body = json.loads(text)
    except ValueError:
        return text
    if isinstance(body, dict) and isinstance(body.get('message'), str):
        return body['message']
    return text


def transport(raw, marker):
    """(problem or None, the JSON text after the marker): exactly one line 'kt-sql: HTTP 400'; the message is
    'ERROR:  P0001: <marker> {...}' with exactly one 'ERROR:' outside the JSON; the JSON closes right before CONTEXT."""
    lines = raw.replace('\r\n', '\n').split('\n')
    http = [l.strip() for l in lines if l.startswith('kt-sql: HTTP')]
    if http != ['kt-sql: HTTP 400']:
        note = ' (HTTP 200 with rows: the transaction COMMITTED, an incident)' if 'kt-sql: HTTP 200' in http else ''
        return f'transport: expected exactly one "kt-sql: HTTP 400" line, got {http or "none"}{note}', None
    msg = unwrap(raw)
    m = re.match(r'^(?:Failed to run sql query: )?ERROR:  ([0-9A-Z]{5}): ', msg)
    if not m:
        return 'transport: the message does not start with an ERROR and its SQLSTATE: ' + msg[:200].replace('\n', ' '), None
    if m.group(1) in ('57014', '55P03'):
        return f'transport: SQLSTATE {m.group(1)} (timeout or lock not obtained): STOP', None
    if m.group(1) != 'P0001':
        return f'transport: SQLSTATE {m.group(1)} (only P0001, the harness RAISE, is a result): ' + msg[:300].replace('\n', ' '), None
    rest = msg[m.end():]
    if not rest.startswith(marker + ' '):
        nr = re.search(r'MUTANT NOT RESTORED (\w+)', rest)
        if nr:
            return f'NOT OK: MUTANT NOT RESTORED {nr.group(1)}', None
        return f'transport: the message is not {marker}: ' + rest[:300].replace('\n', ' '), None
    body = rest[len(marker) + 1:]
    try:
        _, end = json.JSONDecoder().raw_decode(body)
    except ValueError as e:
        return f'transport: {marker} is not complete JSON ({e})', None
    extra = msg[:m.start()].count('ERROR:') + body[end:].count('ERROR:')
    if extra:
        return f"transport: expected exactly one 'ERROR:' outside the result JSON, got {extra + 1}", None
    if not body[end:].startswith('\nCONTEXT:'):
        return f'transport: the JSON does not close right before CONTEXT: {body[end:end + 60]!r}', None
    return None, body


MODES = {'full': 'harness-n.sql', 'structure': 'harness-n-structure.sql'}


def report(raw, expect=None):
    prob, body = transport(raw, 'T4263_RESULT')
    if prob:
        return [prob if prob.startswith('NOT OK') else 'NOT OK: ' + prob], False
    res, _ = json.JSONDecoder().raw_decode(body)
    if not isinstance(res, dict) or res.get('mode') not in MODES:
        return ['NOT OK: T4263_RESULT names no known mode'], False
    mode = res['mode']
    if expect and mode != expect:
        return [f'NOT OK: this is the {mode} call, expected the {expect} call'], False
    names = CONTROLS if mode == 'full' else STRUCTURE_BASE
    mids = [m[0] for m in MUTS] if mode == 'full' else STRUCTURE_MUTANTS
    out, bad = [f'mode: {mode} ({MODES[mode]})'], 0
    n_ctl = n_mut = n_neg = 0
    ctl = res.get('controls')
    if not isinstance(ctl, dict):
        return out + ['NOT OK: no controls object'], False
    for c in names:
        v = ctl.get(c, 'MISSING')
        n_ctl += 1
        ok = v == 'PASS'
        bad += 0 if ok else 1
        out.append(f"{'PASS' if ok else 'FAIL'} {c} {'' if ok else str(v)[:900]}")
    for mid in mids:
        o = res.get('mutant:' + mid)
        if mid in NEG_IDS:
            n_neg += 1
            good = isinstance(o, dict) and o.get('applied') is False and o.get('error') == NOT_APPLIED_ERROR
            bad += 0 if good else 1
            out.append(f"{'NEG_OK' if good else 'NEG_FAILED':14} {mid} (required: applied false, error {NOT_APPLIED_ERROR!r}) -> {json.dumps(o)[:300]}")
            continue
        n_mut += 1
        if not isinstance(o, dict):
            out.append(f'MISSING mutant {mid}')
            bad += 1
            continue
        vals = [str(o.get(c, 'MISSING')) for c in PRIMARY[mid]]
        if o.get('applied') is not True or 'error' in o:
            tag = 'NOT_APPLIED' if o.get('applied') is not True else 'CRASH'
        elif WANT[mid] == 'green':
            tag = 'EQUIV' if all(v == 'PASS' for v in vals) else 'UNEXPECTED_RED'
        elif any(v.startswith('ERROR') or v == 'MISSING' for v in vals):
            tag = 'CRASH'
        elif any(v.startswith('FAIL') for v in vals):
            tag = 'CAUGHT'
        else:
            tag = 'MISSED'
        bad += 0 if tag in ('CAUGHT', 'EQUIV') else 1
        out.append(f'{tag:14} {mid} want={WANT[mid]} -> {json.dumps(o)[:300]}')
    for k in ('top_apply', 'rollback'):
        out.append(f'{k}: {res.get(k)}')
        if res.get(k) != 'ok':
            bad += 1
    if res.get('rollback_restores') is not True:
        out.append('NOT OK: the catalogue after the rollback step differs from the baseline')
        bad += 1
    if mode == 'structure' and res.get('baseline_fp') != res.get('baseline_fp_again'):
        out.append('NOT OK: the fingerprint is not stable (two reads differ)')
        bad += 1
    if mode == 'full' and res.get('fp_after_mutants') is not True:
        out.append('NOT OK: the catalogue after the mutants differs from the baseline')
        bad += 1
    out.append(f"wal_bytes: {res.get('wal_bytes')}  t_start: {res.get('t_start')}  t_end: {res.get('t_end')}")
    out.append(f'controls={n_ctl} mutant_entries={n_mut + n_neg} (real={n_mut} + negative_control_required_not_applied={n_neg}) problems={bad}')
    if n_neg != 1:
        out.append('NOT OK: the negative control is missing')
        return out, False
    if n_ctl == 0 or n_mut == 0:
        out.append('NOT OK: zero tests ran')
        return out, False
    if mode == 'structure':
        out.append('structure: OK' if bad == 0 else 'structure: NOT OK')
    return out, bad == 0


def report_fixtures(raw):
    prob, body = transport(raw, 'T4263N_FIXTURES_OK')
    if prob:
        return ['NOT OK: ' + prob, 'decision: STOP'], False
    res, _ = json.JSONDecoder().raw_decode(body)
    out, ok = [], True
    got = res.get('fx_counts', {})
    for k, want in FIXTURE_EXPECT.items():
        good = got.get(k) == want
        ok &= good
        out.append(f"{'ok ' if good else 'BAD'} {k}: {got.get(k)} (want {want})")
    if res.get('tn_probe') != 'ok':
        ok = False
        out.append(f"BAD tn_probe: {res.get('tn_probe')}")
    probes = {k: res.get(k) for k in ('fixture_ms', 'chain_ms', 'tn_ms')}
    for k, v in probes.items():
        good = isinstance(v, (int, float)) and v > 0
        ok &= good
        out.append(f"{'ok ' if good else 'BAD'} {k}: {v}")
    if ok:
        # each control and each mutant proof: one T-N application and up to three approval chains
        runs = len(CONTROLS) + sum(len(PRIMARY[m[0]]) for m in MUTS) + len(MUTS) + 2
        est = probes['fixture_ms'] + runs * (probes['tn_ms'] + 3 * probes['chain_ms'])
        out.append(f'estimate full call: {est / 1000:.3f} s ({runs} T-N applications)')
        out.append(f"wal_bytes (fixtures call): {res.get('wal_bytes')}")
        out.append('decision: FULL' if est <= 45000 else 'decision: STOP (the full call is estimated over 45 s; no split is built)')
        ok = est <= 45000
    else:
        out.append('NOT OK')
        out.append('decision: STOP')
    return out, ok


def selftest(green_ok=False):
    """report() on canned outputs: the good shapes pass, every violation is refused."""
    ctl = {c: 'PASS' for c in CONTROLS}
    mut = {}
    for mid, *_ in MUTS:
        if mid in NEG_IDS:
            mut['mutant:' + mid] = {'applied': False, 'error': NOT_APPLIED_ERROR, 'want': 'not_applied'}
        elif WANT[mid] == 'green':
            mut['mutant:' + mid] = {**{c: 'PASS' for c in PRIMARY[mid]}, 'applied': True, 'want': 'green'}
        else:
            mut['mutant:' + mid] = {**{c: 'PASS' for c in PRIMARY[mid]}, PRIMARY[mid][0]: 'FAIL: x', 'applied': True, 'want': 'red'}
    good = {'mode': 'full', 'controls': ctl, **mut, 'top_apply': 'ok', 'rollback': 'ok', 'rollback_restores': True, 'fp_after_mutants': True}

    def wrap(res, http='kt-sql: HTTP 400', marker='T4263_RESULT'):
        msg = f'Failed to run sql query: ERROR:  P0001: {marker} ' + json.dumps(res) + '\nCONTEXT:  PL/pgSQL function inline_code_block line 4 at RAISE'
        return json.dumps({'message': msg}) + '\n' + http + '\n'
    cases = [('good', wrap(good), True)]
    bad1 = json.loads(json.dumps(good)); bad1['controls'][CONTROLS[0]] = 'FAIL: x'
    cases.append(('control fails', wrap(bad1), False))
    red = [m[0] for m in MUTS if WANT[m[0]] == 'red'][0]
    bad2 = json.loads(json.dumps(good)); bad2['mutant:' + red] = {**{c: 'PASS' for c in PRIMARY[red]}, 'applied': True, 'want': 'red'}
    cases.append(('mutant missed', wrap(bad2), green_ok))
    bad3 = json.loads(json.dumps(good)); bad3['mutant:noop_probe'] = {'applied': True, 'want': 'not_applied'}
    cases.append(('negative control applied', wrap(bad3), False))
    bad4 = json.loads(json.dumps(good)); bad4['rollback'] = 'ERR P0001 x'
    cases.append(('rollback failed', wrap(bad4), False))
    cases.append(('committed', wrap(good, 'kt-sql: HTTP 200'), False))
    bad5 = json.loads(json.dumps(good)); bad5['mutant:' + red] = {PRIMARY[red][0]: 'ERROR 42883 x', 'applied': True, 'want': 'red'}
    cases.append(('mutant crash', wrap(bad5), False))
    cases.append(('timeout', json.dumps({'message': 'Failed to run sql query: ERROR:  57014: canceling statement'}) + '\nkt-sql: HTTP 400\n', False))
    bad6 = json.loads(json.dumps(good)); bad6['rollback_restores'] = False
    cases.append(('rollback not restoring', wrap(bad6), False))
    wrong = 0
    for name, raw, want in cases:
        _, ok = report(raw)
        print(f"{'ok   ' if ok == want else 'WRONG'} {name}: report ok={ok}, want {want}")
        wrong += ok != want
    fx = {'fx_counts': FIXTURE_EXPECT, 'tn_probe': 'ok', 'fixture_ms': 300, 'chain_ms': 20, 'tn_ms': 15, 'wal_bytes': 1}
    for name, res, want in [('fixtures good', fx, True), ('fixtures count', {**fx, 'fx_counts': {**FIXTURE_EXPECT, 'connections': 1}}, False),
                            ('fixtures probe', {**fx, 'tn_probe': 'ERR x'}, False), ('fixtures slow', {**fx, 'chain_ms': 5000}, False)]:
        _, ok = report_fixtures(wrap(res, marker='T4263N_FIXTURES_OK'))
        print(f"{'ok   ' if ok == want else 'WRONG'} {name}: ok={ok}, want {want}")
        wrong += ok != want
    print(f'selftest: {len(cases) + 4} cases, {wrong} wrong')
    return 1 if wrong else 0


def static_checks():
    problems = []
    for p, text in OUTS.items():
        if p.endswith('.sql'):
            f = casts.findings(text)
            problems += [f'cast {os.path.relpath(p, REPO)} {x}' for x in f]
    # a helper that reads a public table is VOLATILE
    for m in re.finditer(r'CREATE FUNCTION pg_temp\.(\w+)\([^)]*\) RETURNS [^\n]*?LANGUAGE sql (\w+)? ?AS \$h\$(.*?)\$h\$', LIB['helpers'], re.S):
        if re.search(r'FROM public\.', m.group(3)) and (m.group(2) or '').upper() in ('STABLE', 'IMMUTABLE'):
            problems.append(f'helper {m.group(1)} reads a public table and is {m.group(2)}')
    if _ans['findings']:
        problems += [f'answers {x}' for x in _ans['findings']]
    return problems


def main(argv):
    cmd = argv[0] if argv else 'write'
    if cmd == 'write':
        all_mutants(show=True)
        for p, text in OUTS.items():
            os.makedirs(os.path.dirname(p), exist_ok=True)
            open(p, 'w', encoding='utf-8').write(text)
        pr = static_checks()
        for x in pr:
            print('PROBLEM', x)
        print(f'wrote {len(OUTS)} files; controls {len(CONTROLS)}, mutants {len(MUTS)} (negative {len(NEG_IDS)})')
        return 1 if pr else 0
    if cmd == 'check':
        all_mutants(show=True)
        stale = [p for p, text in OUTS.items() if not os.path.exists(p) or open(p, encoding='utf-8').read() != text]
        for p in stale:
            print('STALE', os.path.relpath(p, REPO))
        pr = static_checks()
        for x in pr:
            print('PROBLEM', x)
        print(f"check: {'OK' if not stale and not pr else 'FAILED'} ({len(OUTS)} files, {len(MUTS)} mutants)")
        return 1 if stale or pr else 0
    if cmd == 'report':
        lines, ok = report(open(argv[1], encoding='utf-8').read(), argv[2] if len(argv) > 2 else None)
        print('\n'.join(lines))
        return 0 if ok else 1
    if cmd == 'report-fixtures':
        lines, ok = report_fixtures(open(argv[1], encoding='utf-8').read())
        print('\n'.join(lines))
        return 0 if ok else 1
    if cmd == 'selftest':
        return selftest('--control-green-ok' in argv)
    if cmd == 'dry-wrappers':
        d = argv[1]
        os.makedirs(d, exist_ok=True)
        open(os.path.join(d, 'dry-apply.sql'), 'w').write(header('dry-apply.sql', 'The apply file, then RAISE (nothing kept).') + APPLY
            + "DO $e$ BEGIN RAISE EXCEPTION 'T4263N_APPLY_OK %', jsonb_build_object('version', (SELECT notice_version FROM public.mcp_settings WHERE id), "
              "'ledger', (SELECT count(*) FROM supabase_migrations.schema_migrations WHERE version = '" + T_VERSION + "')); END $e$;\n")
        open(os.path.join(d, 'dry-rollback.sql'), 'w').write(header('dry-rollback.sql', 'The apply file, then the rollback file, then RAISE.') + APPLY + ROLLBACK
            + "DO $e$ BEGIN RAISE EXCEPTION 'T4263N_ROLLBACK_OK %', jsonb_build_object('version', (SELECT notice_version FROM public.mcp_settings WHERE id), "
              "'ledger', (SELECT count(*) FROM supabase_migrations.schema_migrations WHERE version = '" + T_VERSION + "')); END $e$;\n")
        print('wrote dry-apply.sql, dry-rollback.sql in', d)
        return 0
    print(__doc__)
    return 2


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
