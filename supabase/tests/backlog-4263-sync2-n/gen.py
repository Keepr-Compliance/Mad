def proof_fn(i, mid, kind, proof):
    setup, expr = proof
    return f"""CREATE FUNCTION pg_temp.proof_{i}() RETURNS boolean LANGUAGE plpgsql AS $pf$
DECLARE v boolean := false;
BEGIN
  -- {mid}: the variant's text ran and changed what its fragment changes
  BEGIN
    PERFORM pg_temp.tn();
    {setup}
    v := coalesce(({expr}), false);
    RAISE EXCEPTION 'undo-proof';
  EXCEPTION WHEN OTHERS THEN
    IF SQLERRM <> 'undo-proof' THEN v := false; PERFORM pg_temp.put_tx('proof_error:{mid}', SQLSTATE || ' ' || left(SQLERRM, 300)); END IF;
  END;
  RETURN v;
END $pf$;
"""


