   WHERE x.id = p_deal_id AND x.owner_user_id = v_uid /*OWN:get_deal*/ AND x.is_confirmed /*CONF:get_deal*/;
  IF v_deal.id IS NULL THEN
    RETURN '{"not_found":true}'::jsonb;
