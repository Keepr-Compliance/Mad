  v_uid  uuid := auth.uid();
  v_st   jsonb;
  v_deal public.cloud_deals%ROWTYPE;
  v_n    bigint;
BEGIN
  IF v_uid IS NULL THEN
    RETURN '{"not_entitled":true}'::jsonb;
  END IF;
  v_st := public.get_my_cloud_autosave_state();
