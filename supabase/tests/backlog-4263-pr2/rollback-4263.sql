  END LOOP;
  UPDATE public.cloud_deals SET last_synced_at = greatest(last_synced_at, clock_timestamp()) WHERE id = v_deal;   /*CLOCK:parties*/
  RETURN jsonb_build_object('ok', true, 'results', out);
END $f$;
