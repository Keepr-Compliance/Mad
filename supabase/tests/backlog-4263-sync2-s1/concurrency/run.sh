#!/bin/bash
# BACKLOG-4263 S1 two-session controls. TEST DATABASE ONLY. PREREQUISITE: migration 20261123100000 applied (committed).
# Unlike harness-s1.sql these COMMIT fixture rows (one user with random ids per run, an organization, a membership, the
# assignment, two deals, one blob) and remove them in the teardown (always, from the trap, then verified clean).
#   R1  IA writes a new deal and holds its transaction 4 s; IB claims with replace.
#       Expect: the claim waits for the write (server clock: claim end >= write time + 3.5 s; session 1 sleeps 4 s after
#       its write and commits after that), the write applied, IB active afterwards.
#       Mutant (mutant-claim-nolock.sql): the claim without FOR UPDATE on the settings row -> no wait -> FAIL.
#   R2  IA confirms its blob and holds 4 s; IB claims with replace.
#       Expect: the claim waits (claim end >= confirm time + 3.5 s); confirm answered object_missing; IB active afterwards.
#       Mutant (mutant-confirm-nolock.sql): confirm without its settings FOR SHARE -> no wait -> FAIL.
#   R3  (needs one_computer ON) no active computer; IA claims and holds 4 s; IB claims without replace.
#       Expect: IA ok, IB computer_not_active, IA active (exactly one active).
#       Mutant: mutant-claim-nolock.sql -> both see no active computer -> both ok -> FAIL.
#   R4  (needs one_computer ON) IA active; IB takes over and holds 4 s; IA's owed turn-off (with IA's install).
#       Expect: the turn-off waits, then answers computer_not_active; both deals still there; Keepr Cloud still on.
#       Mutant (mutant-off-no-active-check.sql): the turn-off refusal removed -> deals deleted -> FAIL.
#   R5  (needs one_computer ON) IA active turns off and holds 4 s; IB claims with replace.
#       Expect: turn-off success; claim not_entitled; no move row.
# R1 and R2 run with the switch either way. R3-R5 refuse to start unless public.cloud_release_switches.one_computer is
# already true (they never flip it): on the test database that is after the coordinator's flip (after P2 merges).
# Mutants: apply mutant-<x>.sql, re-run the case (expect FAIL), apply pristine-<function>.sql. Each mutant file is one
# CREATE OR REPLACE generated by ../gen.py from the migration text. A mutant on the shared test database is live for
# every lane until the pristine file is applied: run it only inside a coordinator-approved window.
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
K=~/.claude/bin/kt-sql
case "${1:-}" in R1|R2|R3|R4|R5) ;; *) sed -n '2,27p' "$0"; exit 2 ;; esac
CASE="$1"

umask 077
tmp="$(mktemp -d)"
RUN="$(openssl rand -hex 8)"
uid() { python3 -c 'import uuid; print(uuid.uuid4())'; }
A="$(uid)"; O="$(uid)"; M="$(uid)"; IA="$(uid)"; IB="$(uid)"; BLOB=""; SETUP_DONE=0; VERDICT=FAIL
case "$CASE" in R3) ACTIVE=none ;; *) ACTIVE=IA ;; esac

fill() {  # fill <out> <template>...
  local out="$1"; shift
  for f in "$@"; do cat "$here/$f"; echo; done | sed -e "s/__A__/${A}/g" -e "s/__O__/${O}/g" -e "s/__M__/${M}/g" \
    -e "s/__IA__/${IA}/g" -e "s/__IB__/${IB}/g" -e "s/__RUN__/${RUN}/g" -e "s/__BLOB__/${BLOB}/g" -e "s/__ACTIVE__/${ACTIVE}/g" > "$tmp/$out"
}
col() { python3 -c 'import json,sys; print(json.load(sys.stdin)[-1][sys.argv[1]])' "$1"; }

cleanup() {
  rc=$?
  set +e
  trap - EXIT INT TERM
  wait 2>/dev/null
  [ "$INTERRUPTED" = 1 ] && sleep 8
  if [ "$SETUP_DONE" = 1 ]; then
    fill teardown.filled.sql teardown.sql; $K "$tmp/teardown.filled.sql" >/dev/null
    fill verify.filled.sql verify.sql
    v="$($K "$tmp/verify.filled.sql" | python3 -c 'import json,sys; print([r for r in json.load(sys.stdin) if "verdict" in r][-1]["verdict"])')"
    if [ "$v" != "clean" ]; then echo "TEARDOWN NOT CLEAN (run ${RUN}): fixture rows are left" >&2; rc=1; else echo "teardown verified clean"; fi
  fi
  rm -rf "$tmp"
  echo "${CASE}: ${VERDICT}"
  [ "$VERDICT" = PASS ] || rc=1
  exit $rc
}
INTERRUPTED=0
trap cleanup EXIT
trap 'INTERRUPTED=1; exit 130' INT TERM

fill setup.filled.sql setup.sql
SETUP_DONE=1
out="$($K "$tmp/setup.filled.sql")"
BLOB="$(echo "$out" | col blob)"; ON="$(echo "$out" | col one_computer)"
[ -n "$BLOB" ] || { echo "setup failed: $out" >&2; exit 1; }
case "$CASE" in R3|R4|R5) [ "$ON" = "True" ] || { echo "${CASE} needs one_computer on (it is ${ON}); not run" >&2; exit 1; } ;; esac

pair() {
  ( $K "$tmp/$1" > "$tmp/first.out" 2>&1 || true ) &
  p1=$!
  sleep 1
  ( $K "$tmp/$2" > "$tmp/second.out" 2>&1 || true ) &
  p2=$!
  wait $p1 $p2
  echo "first:  $(cat "$tmp/first.out")"
  echo "second: $(cat "$tmp/second.out")"
}
case "$CASE" in
  R1) fill a.sql as-user.sql r1-write-hold.sql; fill b.sql gate.sql as-user.sql claim-ib-replace.sql; pair a.sql b.sql ;;
  R2) fill a.sql as-user.sql r2-confirm-hold.sql; fill b.sql gate.sql as-user.sql claim-ib-replace.sql; pair a.sql b.sql ;;
  R3) fill a.sql as-user.sql r3-claim-ia-hold.sql; fill b.sql gate.sql as-user.sql r3-claim-ib.sql; pair a.sql b.sql ;;
  R4) fill a.sql as-user.sql r4-claim-ib-hold.sql; fill b.sql gate.sql as-user.sql r4-off-ia.sql; pair a.sql b.sql ;;
  R5) fill a.sql as-user.sql r5-off-ia-hold.sql; fill b.sql gate.sql as-user.sql r5-claim-ib.sql; pair a.sql b.sql ;;
esac
fill assert.filled.sql assert.sql
$K "$tmp/assert.filled.sql" > "$tmp/state.out"
echo "state:  $(cat "$tmp/state.out")"

VERDICT="$(python3 - "$CASE" "$tmp/first.out" "$tmp/second.out" "$tmp/state.out" "$IA" "$IB" <<'PY'
import json, sys
from datetime import datetime
case, f1, f2, fs, ia, ib = sys.argv[1:7]
def ts(x):
    try:
        return datetime.fromisoformat(str(x).replace('Z', '+00:00'))
    except Exception:
        return None
def waited(a, b):
    t0, t1 = ts(a.get('t_write')), ts(b.get('t_end'))
    return t0 is not None and t1 is not None and (t1 - t0).total_seconds() >= 3.5
def last_row(p):
    t = open(p).read()
    try:
        r = json.loads(t.split('\nkt-sql:')[0])
        return r[-1] if isinstance(r, list) and r else {}
    except Exception:
        return {}
a, b, st = last_row(f1), last_row(f2), last_row(fs).get('j', {})
ra, rb = a.get('r') or {}, b.get('r') or {}
raw = open(f1).read() + open(f2).read()
ok = '40P01' not in raw
if case == 'R1':
    ok = ok and (ra.get('results') or [{}])[0].get('status') == 'applied' and rb.get('ok') is True \
        and waited(a, b) and st.get('active') == ib and st.get('deal_r1') == 1
elif case == 'R2':
    ok = ok and ra.get('error') == 'object_missing' and rb.get('ok') is True and waited(a, b) \
        and st.get('active') == ib
elif case == 'R3':
    ok = ok and ra.get('ok') is True and rb.get('error') == 'computer_not_active' and st.get('active') == ia and st.get('moves') == 0
elif case == 'R4':
    ok = ok and ra.get('ok') is True and rb.get('error') == 'computer_not_active' and st.get('deals') == 2 \
        and st.get('enabled') is True and st.get('active') == ib
elif case == 'R5':
    ok = ok and ra.get('success') is True and rb.get('error') == 'not_entitled' and st.get('moves') == 0 and st.get('deals') == 0
print('PASS' if ok else 'FAIL')
PY
)"
