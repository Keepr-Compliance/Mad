def case_fn(cid, body):
    return (f"CREATE FUNCTION pg_temp.{cid}() RETURNS text LANGUAGE plpgsql AS $c$\n"
            "DECLARE v jsonb; ra jsonb; rb jsonb; before text; after text; x uuid; x_t timestamptz;\nBEGIN"
            + body + "\nEND $c$;\n")


def run_cases(var):
    """plpgsql that runs every case, each in a subtransaction that is undone, results into the jsonb variable var."""
    return ''.join(f"""    BEGIN
      res := pg_temp.{c}();
      RAISE EXCEPTION 'undo-case';
    EXCEPTION WHEN OTHERS THEN
      IF SQLERRM <> 'undo-case' THEN res := 'ERROR ' || SQLSTATE || ' ' || left(SQLERRM, 400); END IF;
    END;
    {var} := {var} || jsonb_build_object('{c}', res);
""" for c in ORDER)


def dq(s, tag):
    assert tag not in s
    return tag + '\n' + s + '\n' + tag


